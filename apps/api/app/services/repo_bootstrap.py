@dataclass(frozen=True)
class BackendTemplate:
    """One backend framework this module can scaffold real boilerplate
    for. Add a new backend by adding one of these to _BACKEND_TEMPLATES —
    generate_scaffold_files, the README, .gitignore, and workspace-root
    generation all pick it up with no further changes.

    `is_node_workspace` marks a JS/TS backend (Express, and any future
    Node-based one) so it (a) is folded into the root npm workspace
    alongside frontend/, and (b) contributes to .gitignore's Node section
    rather than its Python one — the opposite of a Python backend like
    FastAPI, which keeps its own separate venv/pip flow outside the JS
    workspace entirely."""

    name: str
    markers: tuple[str, ...]
    is_node_workspace: bool
    build: Callable[[Project, ProjectEngineeringSetup], list[ScaffoldFile]]


_BACKEND_TEMPLATES: list[BackendTemplate] = [
    BackendTemplate(name="FastAPI", markers=_FASTAPI_MARKERS, is_node_workspace=False, build=lambda project, setup: _fastapi_scaffold(project)),
    BackendTemplate(name="Express", markers=_EXPRESS_MARKERS, is_node_workspace=True, build=_express_scaffold),
]


def _match_backend_template(setup: ProjectEngineeringSetup) -> BackendTemplate | None:
    value = setup.backend_framework
    if not value:
        return None
    lowered = value.lower()
    for template in _BACKEND_TEMPLATES:
        if any(marker in lowered for marker in template.markers):
            return template
    return None


def _slug(name: str) -> str:
    return "".join(c.lower() if c.isalnum() else "-" for c in name).strip("-") or "project"


def _latest_approved_content(db: Session, project: Project, artifact_type: str) -> str | None:
    artifact = (
        db.query(Artifact)
        .filter(Artifact.project_id == project.id, Artifact.artifact_type == artifact_type, Artifact.status == ArtifactStatus.APPROVED)
        .order_by(Artifact.updated_at.desc())
        .first()
    )
    if artifact is None or artifact.current_version is None:
        return None
    return artifact.current_version.content_markdown


def generate_scaffold_files(db: Session, *, project: Project, setup: ProjectEngineeringSetup) -> list[ScaffoldFile]:
    """The full set of files a bootstrap commit writes — deterministic
    given `project`/`setup`/this project's currently-approved documents.
    Never touches GitHub; a pure, independently-testable function."""
    has_frontend = _matches(setup.frontend_framework, _NEXTJS_MARKERS)
    backend_template = _match_backend_template(setup)
    has_backend = backend_template is not None
    backend_is_node = bool(backend_template and backend_template.is_node_workspace)
    hld_content = _latest_approved_content(db, project, "hld_document")
    solution_content = _latest_approved_content(db, project, "solution_options_doc")
    standards_content = _coding_standards_doc(setup)

    workspace_members: list[str] = []
    if has_frontend:
        workspace_members.append("frontend")
    if backend_is_node:
        workspace_members.append("backend")

    files: list[ScaffoldFile] = [
        ScaffoldFile(
            "README.md",
            _readme(
                project, setup, has_frontend_scaffold=has_frontend, has_backend_scaffold=has_backend,
                backend_framework_name=backend_template.name if backend_template else None,
                workspace_members=workspace_members,
                has_solution_doc=solution_content is not None, has_coding_standards=standards_content is not None,
            ),
        ),
        ScaffoldFile(
            ".gitignore",
            _gitignore(has_node=has_frontend or backend_is_node, has_python=has_backend and not backend_is_node),
        ),
    ]

    if has_frontend:
        files += _nextjs_scaffold(project)
    if backend_template is not None:
        files += backend_template.build(project, setup)
    if not has_frontend and not has_backend:
        # Generic fallback — no framework this module knows how to scaffold
        # for real; still give the repo a sane starting layout rather than
        # nothing beyond README/.gitignore.
        files.append(ScaffoldFile("src/.gitkeep", ""))

    if workspace_members:
        # Workspace root — see _root_workspace_package_json's docstring for
        # why this is what actually makes these folders one workspace.
        files.append(ScaffoldFile("package.json", _root_workspace_package_json(project, workspace_members=workspace_members)))

    if hld_content:
        files.append(ScaffoldFile("docs/HLD.md", hld_content))
    if solution_content:
        files.append(ScaffoldFile("docs/SOLUTION_DISCOVERY.md", solution_content))
    if standards_content:
        # This project's own coding standards + agent guardrails, carried
        # into the repository itself — see _coding_standards_doc's
        # docstring for why this matters beyond what Agent Context Builder
        # already injects invisibly at runtime.
        files.append(ScaffoldFile("docs/CODING_STANDARDS.md", standards_content))

    return files


class RepoBootstrapError(Exception):
    """A precondition failed before any GitHub write was attempted, or a
    real GitHubIntegrationError occurred partway through — the caller
    (see the route) turns this into an HTTP error either way. Some files
    may already have been committed when this is raised partway through
    `push_scaffold` (see its own docstring) — `commits` on this exception
    reports exactly which, so a caller can tell "nothing happened" apart
    from "the repo is now partially bootstrapped"."""

    def __init__(self, message: str, *, commits: list["BootstrapCommit"] | None = None):
        super().__init__(message)
        self.commits = commits or []


@dataclass
class BootstrapCommit:
    path: str
    commit_sha: str


@dataclass
class BootstrapResult:
    branch: str
    commits: list[BootstrapCommit] = field(default_factory=list)


def push_scaffold(token: str, repository: Repository, files: list[ScaffoldFile]) -> BootstrapResult:
    """Writes every scaffold file as its own commit, directly on
    `repository.default_branch` (see this module's HARD RULE above for
    why that's correct here and nowhere else). Each file is created
    (never updated — a genuinely empty repo has nothing to update) via
    the exact same github_integration.create_or_update_file GitHub
    already uses for every other write in this codebase; nothing here
    talks to GitHub any differently, only *where* it's allowed to write.

    Stops at the first failure and raises RepoBootstrapError carrying
    whatever commits already landed — a caller can't accidentally retry
    into duplicate commits (GitHub would reject a second create at the
    same path with no `sha`), and the repository is left in a real,
    inspectable state either way, never silently half-done with no
    record of what happened."""
    branch = repository.default_branch or "main"
    commits: list[BootstrapCommit] = []
    for f in files:
        try:
            commit_sha = github_api.create_or_update_file(
                token, repository.owner, repository.name, f.path,
                content=f.content, message=f"Bootstrap: add {f.path}", branch=branch,
            )
        except github_api.GitHubIntegrationError as exc:
            raise RepoBootstrapError(f"Failed writing {f.path}: {exc}", commits=commits) from exc
        commits.append(BootstrapCommit(path=f.path, commit_sha=commit_sha))
    return BootstrapResult(branch=branch, commits=commits)
