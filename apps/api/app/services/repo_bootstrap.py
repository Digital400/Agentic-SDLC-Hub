"""RepoBootstrapService — turns a brand-new, genuinely EMPTY GitHub
repository into a real, runnable starter project, using this project's
own already-approved documents and Project Engineering Setup (technology
stack) as the source of truth — not a fresh model call. See
app/api/routes/repo_bootstrap.py for the one endpoint that calls this.

Deliberately deterministic, template-based scaffolding — no LLM call
anywhere in this module. Mirrors app/services/repo_context_builder.py's
own reasoning for staying non-AI: which starter files a known framework
needs is a mechanical fact, not a judgment call, and a scaffold a human
is about to build real work on top of should never be something a model
might hallucinate wrong.

HARD RULE, and the one deliberate, narrow exception to
app/services/github_integration.py's "never write to a repository's
default branch" invariant (see that module's own docstring): GitHub's
Contents API has no way to open a PR into a base branch that does not
exist yet, and a genuinely empty repository has NO branch at all — its
default branch is only a name until the first commit lands. There is
therefore no way to bootstrap an empty repository through this
codebase's normal branch+PR flow; the very first commit MUST be made
directly against the repository's configured default_branch, which is
exactly what creates it. This module's own bootstrap_repository is the
ONLY caller in this codebase allowed to do that, and only after the
caller (see the route) has independently re-verified the repository is
still empty immediately before writing.

FRAMEWORK REGISTRY: backend frameworks are looked up in _BACKEND_TEMPLATES
below rather than a hand-written if/elif chain — adding real boilerplate
for a new backend framework means adding one BackendTemplate entry there
(markers to match, whether it's a JS/TS workspace member, and a build
function), and generate_scaffold_files/README/.gitignore/workspace-root
generation all pick it up automatically. The frontend side stays a single
if-check (has_frontend) since, as of this module, Next.js is the only
frontend template — the same registry shape can grow a
_FRONTEND_TEMPLATES list the same way if/when a second one is added.
"""

